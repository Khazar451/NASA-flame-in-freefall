import { useEffect, useState } from 'react';
import { useDataset } from './data';
import AtmosphereMap from './views/AtmosphereMap';
import Ranking from './views/Ranking';
import Results from './views/Results';
import Ask from './views/Ask';

const TABS = [
  { id: 'map', label: 'Atmosphere map' },
  { id: 'ranking', label: 'Ranking' },
  { id: 'results', label: 'Test results' },
  { id: 'ask', label: 'Ask' },
] as const;
type TabId = (typeof TABS)[number]['id'];

const tabFromHash = (): TabId => {
  const id = window.location.hash.slice(1);
  return TABS.some((t) => t.id === id) ? (id as TabId) : 'map';
};

export default function App() {
  const { data, error } = useDataset();
  const [tab, setTab] = useState<TabId>(tabFromHash);

  useEffect(() => {
    const onHash = () => setTab(tabFromHash());
    window.addEventListener('hashchange', onHash);
    return () => window.removeEventListener('hashchange', onHash);
  }, []);

  return (
    <div className="shell">
      <header className="masthead">
        <a className="brand" href="#map">
          {/* A flame in freefall is a sphere: with no "up" for hot gas to rise, it burns evenly around its fuel. */}
          <svg className="mark" viewBox="0 0 52 52" aria-hidden="true">
            <circle cx="26" cy="26" r="24" fill="none" stroke="var(--ink)" strokeWidth="1.5" />
            <circle cx="26" cy="26" r="24" fill="none" stroke="var(--ink)" strokeWidth="1.5" strokeDasharray="1.5 5" transform="scale(0.78)" style={{ transformOrigin: 'center' }} />
            <circle cx="26" cy="26" r="11" fill="var(--accent)" />
            <circle cx="26" cy="26" r="4" fill="var(--ember)" />
          </svg>
          <div>
            <p className="eyebrow">NASA Space Apps 2026</p>
            <h1>Flame in Freefall</h1>
            <p>NASA microgravity combustion experiments, read for crew fire safety</p>
          </div>
        </a>
        <nav aria-label="Views">
          {TABS.map((t, i) => (
            <a key={t.id} href={`#${t.id}`} aria-current={tab === t.id ? 'page' : undefined}>
              <span aria-hidden="true">{String(i + 1).padStart(2, '0')}</span>
              {t.label}
            </a>
          ))}
        </nav>
      </header>

      {data && data.sampleRows > 0 && (
        <p className="notice" role="status">
          <strong>Placeholder data.</strong> {data.sampleRows} of {data.tests.length} test rows are randomly
          generated stand-ins, not NASA results. Run <code>npm run sync-data</code> to load the pipeline output
          from <code>data/out/</code>.
        </p>
      )}

      <main>
        {error && (
          <p className="notice error" role="alert">
            {error} Run <code>npm run sync-data</code> to copy investigations.json and tests.json from{' '}
            <code>data/out/</code>.
          </p>
        )}
        {!data && !error && <p className="quiet">Loading data…</p>}
        {data && tab === 'map' && <AtmosphereMap data={data} />}
        {data && tab === 'ranking' && <Ranking data={data} />}
        {data && tab === 'results' && <Results data={data} />}
        {tab === 'ask' && <Ask />}
      </main>

      <footer className="colophon">
        <p>
          <span className="eyebrow">Data</span>
          NASA Physical Sciences Informatics (PSI), Combustion Science
          {data && `: ${data.investigations.length} investigations and ${data.tests.length.toLocaleString('en-US')} test rows`}.
          Every number on this site is read from NASA's tables and reports, and each test keeps its source file and row.
        </p>
        <p>
          <span className="eyebrow">Use of AI</span>
          An AI model proposed each investigation's role and fuel type, which our domain lead then reviewed, and
          it words the answers on the Ask tab from quoted sources. AI coding assistants helped write the code. No
          measured value is generated by AI.
        </p>
        <p>
          <span className="eyebrow">Method</span>
          Scores on the ranking are a weighted sum you can change, not a model's opinion.{' '}
          <a href="https://github.com/Khazar451/NASA-flame-in-freefall" target="_blank" rel="noreferrer">
            Code, data and method on GitHub
          </a>
          .
        </p>
      </footer>
    </div>
  );
}
